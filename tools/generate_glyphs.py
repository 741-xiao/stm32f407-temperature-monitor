"""Regenerate the LCD's 24px Chinese subset with Pillow and Windows SimHei."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parents[1]
source = "".join((root / name).read_text(encoding="utf-8") for name in
                 ("Main/main_sensor.c", "Main/app_config.h"))
characters = sorted({c for c in source if '\u4e00' <= c <= '\u9fff'})
font = ImageFont.truetype("C:/Windows/Fonts/simhei.ttf", 22)
lines = ["/* Generated by tools/generate_glyphs.py; UTF-8 Unicode -> 24x24 bitmap. */",
         "static const struct { u16 code; u32 rows[24]; } app_glyphs[] = {"]
for character in characters:
    canvas = Image.new("L", (24, 24))
    draw = ImageDraw.Draw(canvas)
    box = draw.textbbox((0, 0), character, font=font)
    draw.text(((24 - (box[2] - box[0])) // 2 - box[0],
               (24 - (box[3] - box[1])) // 2 - box[1]), character, font=font, fill=255)
    rows = [sum(1 << (23 - x) for x in range(24) if canvas.getpixel((x, y)) >= 100)
            for y in range(24)]
    lines.append(f"    {{0x{ord(character):04X}, {{" + ",".join(f"0x{r:06X}" for r in rows) + "}}," + f" /* {character} */")
lines.append("};")
(root / "USER/Chinese/app_glyphs.h").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Generated {len(characters)} LCD glyphs")
